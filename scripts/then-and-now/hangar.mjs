// The Docking Bay (the hub) and the Hangar Ring: the first biome, from Wren's arrival to Ossie's choice and the dead lift.
// Legend in rooms.mjs. Heights: a full jump rises 3 tiles, so floors you climb are never more than 3 rows apart.
// row(cols, left, inner, right): one row, the inner part padded with spaces so the drawings cannot be off by a column.
const wall = (cols) => "#".repeat(cols);
const row = (cols, left, inner = "", right = "#") => {
  if (inner.length > cols - 2) throw new Error(`row too long: "${inner}"`);
  return left + inner.padEnd(cols - 2) + right;
};
const empty = (cols, n) => Array.from({ length: n }, () => row(cols, "#"));

